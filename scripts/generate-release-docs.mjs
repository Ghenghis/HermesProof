#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadReleaseFacts } from "../src/core/release-facts.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const defaultRoot = path.resolve(here, "..");

function asList(values) {
  return values.map((value) => `- \`${value}\``).join("\n");
}

export async function renderReleaseDocs({ root = defaultRoot } = {}) {
  const facts = await loadReleaseFacts({ root });
  const markdown = `<!-- GENERATED by scripts/generate-release-docs.mjs. Do not edit by hand. -->
# Current release facts

HermesProof **${facts.version}** ships **${facts.servers.core.tools} core MCP tools** and
**${facts.servers.composite.tools} governed composite MCP tools**. The composite server integrates
**Serena ${facts.serena.version}** with ${facts.serena.cataloguedTools} catalogued tools,
${facts.serena.desktopActiveTools} active desktop tools, ${facts.serena.governedLspTools}
lock-governed semantic/LSP tools, and **${facts.serena.rawMutationTools} unrestricted mutation tools**.

- GitLab project: ${facts.gitlab.projectUrl}
- GitLab Pages: ${facts.gitlab.pagesUrl}
- Publication authority: GitLab only
- Release tag: \`${facts.releaseTag}\`
- Truth gates: ${facts.truthGates}
- Minimum Node.js: ${facts.nodeMinimum}
- Preferred local inference: LM Studio LM Link
- Local fallback: Ollama

## Default client targets

${asList(facts.install.defaultTargets)}

## Capability profiles

${asList(facts.capabilityProfiles)}
`;
  const files = new Map([
    [path.join(root, "docs", "GENERATED_RELEASE_FACTS.md"), markdown],
    [path.join(root, "site", "release-facts.json"), JSON.stringify(facts, null, 2) + "\n"],
  ]);
  for (const name of [
    "ecosystem-e2e.svg",
    "updater-lifecycle-animated.svg",
    "capability-pack-flow.svg",
    "windows-install-flow.svg",
  ]) {
    files.set(
      path.join(root, "site", "diagrams", name),
      await fs.readFile(path.join(root, "docs", "diagrams", name), "utf8"),
    );
  }
  return {
    markdown,
    json: facts,
    files,
  };
}

export async function writeReleaseDocs({ root = defaultRoot } = {}) {
  const rendered = await renderReleaseDocs({ root });
  for (const [file, content] of rendered.files) {
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, content, "utf8");
  }
  return { ok: true, written: [...rendered.files.keys()] };
}

export async function checkReleaseDocs({ root = defaultRoot } = {}) {
  const rendered = await renderReleaseDocs({ root });
  const drift = [];
  for (const [file, expected] of rendered.files) {
    let actual;
    try {
      actual = await fs.readFile(file, "utf8");
    } catch {
      actual = null;
    }
    if (actual !== expected) drift.push(path.relative(root, file).replaceAll("\\", "/"));
  }
  return { ok: drift.length === 0, drift };
}

async function main() {
  const check = process.argv.includes("--check");
  const result = check ? await checkReleaseDocs() : await writeReleaseDocs();
  process.stdout.write(JSON.stringify(result, null, 2) + "\n");
  if (!result.ok) process.exitCode = 1;
}

if (
  path.resolve(process.argv[1] || "").toLowerCase() ===
  path.resolve(fileURLToPath(import.meta.url)).toLowerCase()
) {
  await main();
}
